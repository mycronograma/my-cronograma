/**
 * Nexora Type Definitions
 * Central type definitions for the study optimization platform
 */

// ============================================
// User Types
// ============================================

export interface User {
  id: string;
  email: string;
  name: string;
  avatar?: string;
  
  // Gamification (Consistência — incentivo básico)
  xp: number;           // Acumula 1 XP por minuto estudado
  level: number;        // Nível baseado em XP de consistência
  streak: number;
  longestStreak: number;
  lastStudyDate?: Date;
  
  // Prontidão para a Prova (Foco Principal)
  globalReadinessScore: number;  // Média ponderada das proficiências (0-1000)
  targetExam: string;            // Ex: 'ENEM', 'FUVEST', 'CONCURSO'
  staminaScore: number;          // Regularidade de estudo (0-100)
  
  // Preferences
  dailyGoalHours: number;
  preferredStart: string;
  preferredEnd: string;
  maxBlockMinutes: number;
  breakMinutes: number;
  
  // AI Settings
  aiDifficulty: AIDifficulty;
  focusMode: boolean;
  
  createdAt: Date;
  updatedAt: Date;
}

export type AIDifficulty = 'easy' | 'medium' | 'hard' | 'adaptive';
export type UserLearningLevel = 'iniciante' | 'intermediario' | 'avancado';
export type StudySessionKind = 'AULA' | 'EXERCICIOS' | 'REVISAO' | 'SIMULADO' | 'ANALISE' | 'LIVRE';

// ============================================
// Subject Types
// ============================================

export interface Subject {
  id: string;
  userId: string;
  name: string;
  color: string;
  icon: string;
  studyPrefs?: StudyPreferences;
  area?: string;
  nivel?: string;
  pesoNoExame?: number;
  enemWeight?: number;       // 0-1, used for ENEM weighted scheduling
  prerequisitos?: string[];
  topicos?: string[];
  tipo?: string;
  
  // Study parameters
  priority: number;          // 1-10 (alias de examWeight visual)
  difficulty: number;        // 1-10
  targetHours: number;       // Weekly target
  completedHours: number;
  
  // Proficiência (Motor de Aprovação)
  proficiencyScore: number;  // 0-1000, atualizado via sessões de exercícios
  examWeight: number;        // 0-10, peso da matéria no vestibular alvo
  
  // Progress
  totalHours: number;
  sessionsCount: number;
  averageScore: number;
  
  isActive: boolean;
  createdAt: Date;
  updatedAt: Date;
}

export interface StudyPreferences {
  hoursPerDay: number;
  weeklyHours?: number;
  dailyHoursByWeekday?: DailyHoursByWeekday;
  daysOfWeek: number[];
  mode: 'random' | 'exam';
  examDate?: string;
  startDate?: string;
  goal?: 'enem' | 'medicina' | 'concurso' | 'outros';
  userLevel?: UserLearningLevel;
  blockDurationMinutes?: number;
  focusBlockMinutes?: number;
  breakDurationMinutes?: number;
  hardSubjectsPeriodPreference?: HardSubjectsPeriodPreference;
  studyStyle?: StudyStylePreference;
  studyContentPreference?: StudyContentPreference;
  intensity?: StudyIntensityLevel;
  dailyAvailabilityByWeekday?: DailyAvailabilityByWeekday;
  scheduleMode?: 'dynamic' | 'fixed_weekly';
  weeklyTemplate?: Record<string, string[]>;
}

// ============================================
// Study Block Types
// ============================================

export type StudyBlockType =
  | 'AULA'
  | 'EXERCICIOS'
  | 'REVISAO'
  | 'SIMULADO_AREA'
  | 'SIMULADO_COMPLETO'
  | 'ANALISE';

export interface StudyBlock {
  id: string;
  userId: string;
  subjectId: string;
  subject?: Subject;
  
  // Timing
  date: Date;
  /** Horário planejado de início ("09:00"). Não muda ao concluir. */
  startTime: string;
  /** Horário planejado de fim ("09:50"). Não muda ao concluir. */
  endTime: string;
  /** Duração planejada, em minutos. Não muda ao concluir. */
  durationMinutes: number;
  /**
   * Minutos que a pessoa realmente estudou, quando o bloco foi concluído.
   * Antes esse valor sobrescrevia `durationMinutes` e `endTime`, e a agenda
   * passava a mostrar o plano errado ("09:00 - 19:08" para um bloco de 50
   * minutos concluído às 19:08). Agora o plano fica intacto e o real mora aqui.
   */
  actualMinutes?: number;
  
  // Roadmap metadata
  sessionType?: 'teoria' | 'pratica' | 'revisao' | 'simulado';
  phase?: string;
  area?: string;
  type?: StudyBlockType;
  description?: string;
  sequenceIndex?: number;
  relatedSubjectId?: string;
  topicName?: string;
  pedagogicalStepIndex?: number;
  pedagogicalStepTotal?: number;
  adaptiveScore?: number;
  
  // Status
  status: BlockStatus;
  isBreak: boolean;
  isAutoGenerated: boolean;
  originalDate?: Date;
  completedAt?: Date;
  rescheduleCount?: number;
  
  createdAt: Date;
  updatedAt: Date;
}

export type BlockStatus =
  | 'scheduled'
  | 'in-progress'
  | 'completed'
  | 'skipped'
  | 'rescheduled';

// ============================================
// Study Session Types
// ============================================

export interface StudySession {
  id: string;
  userId: string;
  subjectId: string;
  blockId?: string;
  subject?: Subject;
  
  // Timing (sempre baseado em timestamps absolutos para precisão)
  startedAt: Date;        // Timestamp real de início (Date.now())
  endedAt?: Date;         // Timestamp real de fim
  plannedMinutes: number; // Duração planejada
  actualMinutes: number;  // Tempo líquido real (descontando pausas)
  pausedMinutes: number;  // Total de minutos em pausa
  
  // Desempenho em exercícios
  performance?: {
    questionsDone: number;
    correctAnswers: number;
    difficulty: 'EASY' | 'MEDIUM' | 'HARD';
  };
  
  // Métricas legadas (mantidas para compatibilidade)
  focusScore: number;        // 0-100
  productivityScore: number; // 0-100
  accuracyRate?: number;     // 0-1
  errorRate?: number;        // 0-1
  sessionType?: StudySessionKind;
  difficultyScore?: number;  // 1-10
  correctAnswers?: number;
  totalQuestions?: number;
  notes?: string;
  
  // Resultados calculados
  xpEarned: number;              // XP de consistência (1 XP/min)
  proficiencyDelta?: number;     // Variação de proficiência (+/-) gerada por esta sessão
  
  createdAt: Date;
}

